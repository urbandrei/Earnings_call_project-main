INCREMENT_TEX = r"""% Generated by make_main_tables.py from data/results/result_table_8.csv.
\begin{table*}[t]
\centering
\scriptsize
\setlength{\tabcolsep}{3pt}
\begin{tabular}{llrrrr}
\toprule
Target, split & Model & $\tau$=3 & $\tau$=7 & $\tau$=15 & $\tau$=30 \\
\midrule
@BODY@
\bottomrule
\end{tabular}
\caption{\textbf{Increment over the price-only reference.} Relative reduction of
test MSE on $\Delta v$ (\%) against the past-volatility ridge on the same calls,
with a 95\% percentile bootstrap interval that resamples companies (1000 draws).
Positive values favor the content model. The 2\% margin and the reading rule were
fixed before the table was computed. A dagger marks an upper bound below the margin
(no meaningful benefit), an asterisk a lower bound above it (improvement), and
unmarked cells are inconclusive. HAR-RV is shown against the same reference. The
forward-looking target starts the post window one session later, so no target
return begins before the call has ended.}
\label{tab:increment}
\end{table*}
"""


def increment_table() -> None:
    t8 = pd.read_csv(R / "result_table_8.csv")
    q = t8[(t8.target == "dv") & (t8.reference == "price_ridge")]
    marks = {"improvement": "*", "no meaningful benefit": r"\dag", "inconclusive": ""}
    names = {
        "HAR": "HAR-RV",
        "S2_text": "S2 text ridge + vol",
        "S3_audio": "S3 audio ridge + vol",
        "S4_fusion": "S4 stack fusion",
    }
    blocks = [
        ("measured", "temporal", "Measured anchor, temporal"),
        ("measured", "combined", "Measured anchor, date-ordered disjoint"),
        ("measured", "ticker_disjoint", "Measured anchor, ticker-disjoint"),
        ("origin", "temporal", "Forward-looking, temporal"),
        ("origin", "combined", "Forward-looking, date-ordered disjoint"),
        ("origin", "ticker_disjoint", "Forward-looking, ticker-disjoint"),
    ]
    rows: list[str] = []
    for i, (anchor, split, label) in enumerate(blocks):
        if i:
            rows.append(r"\midrule")
        b = q[(q.anchor == anchor) & (q.split == split)]
        for j, (model, name) in enumerate(names.items()):
            cells = []
            for h in H:
                r = b[(b.model == model) & (b.horizon == h)].iloc[0]
                cell = f"{100 * r.rel_reduction:+.0f} [{100 * r.ci_lo:+.0f}, {100 * r.ci_hi:+.0f}]"
                cells.append(cell.replace("-", "$-$") + marks[r.verdict])
            head = label if j == 0 else ""
            rows.append(f"{head} & {name} & " + " & ".join(cells) + r" \\")
    (OUT / "increment.tex").write_text(
        INCREMENT_TEX.replace("@BODY@", NL.join(rows)), encoding="utf-8"
    )


