"""Generate the main-text tables of the condensed paper from the result CSVs.

Run from the repository root:  uv run python paper/tables/make_main_tables.py
Writes paper/tables/{grid_main,controls_main,repro_controls_main,lookahead_main}.tex.
Every cell is read from data/results/*.csv (run ids in the CSVs' manifests under
artifacts/runs/); the reproduction block reads the T6R.4 control values that
tables/repro_controls.tex curates, so the two tables cannot drift apart.
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
R = ROOT / "data" / "results"
OUT = Path(__file__).resolve().parent
H = [3, 7, 15, 30]
NL = "\n"


def f3(x: float) -> str:
    return f"{x:.3f}".replace("-", "$-$")


def f2(x: float) -> str:
    return f"{x:.2f}".replace("-", "$-$")


def pct(a: float, b: float) -> str:
    p = (b / a - 1) * 100
    s = f"{p:+.0f}" if abs(p) >= 0.5 else "0"
    return s.replace("-", "$-$") + r"\%"


# --------------------------------------------------------------------------- grid
GRID_TEX = r"""% Generated by make_main_tables.py from data/results/result_table_{1,2,4}.csv.
% FinCall-Surprise, Delta-v target, R^2_OOS vs persistence (test). Canonical ridge/structural
% model per stage; * / dag = Holm-significantly better / worse than Stage 1 (p<0.05).
\begin{table}[t]
\centering
\footnotesize
\setlength{\tabcolsep}{4pt}
\begin{tabular}{lrrrr}
\toprule
Model & $\tau$=3 & $\tau$=7 & $\tau$=15 & $\tau$=30 \\
\midrule
@BODY@
\bottomrule
\end{tabular}
\caption{\textbf{The ladder on FinCall-Surprise.} \Rtwo{} vs.\ persistence on
$\Delta v$ (test). Persistence is 0 by construction, and the train-mean intercept
is the featureless floor. One pre-registered canonical model per stage (the Stage-3
ridge uses WavLM and eGeMAPS). An asterisk or dagger marks a Holm-corrected
Diebold--Mariano result better or worse than Stage~1 ($p<0.05$). Adding text or
audio to the past-volatility ridge (S0$'$) lowers \Rtwo{} in every cell. The full
grid, MAEC, level-$v$, MSE and the MLP heads are in Appendix~\ref{app:complete}.}
\label{tab:grid}
\end{table}
"""


def grid_main() -> None:
    t1 = pd.read_csv(R / "result_table_1.csv")
    t4 = pd.read_csv(R / "result_table_4.csv")
    t2 = pd.read_csv(R / "result_table_2.csv")
    rows: list[str] = []
    for split, label in (
        ("temporal", "Temporal split ($n{=}483$)"),
        ("ticker_disjoint", r"\tickerdisjoint{} split ($n{=}484$)"),
    ):
        rows.append(r"\multicolumn{5}{l}{\textit{" + label + r"}}\\")
        q1 = t1[
            (t1.dataset == "fincall")
            & (t1.convention == "trading")
            & (t1.segment == "test")
            & (t1.target == "dv")
            & (t1.split == split)
        ]
        for model, name in (("train_mean", "S0 train mean"), ("har", "S0 HAR-RV")):
            v = [float(q1[(q1.model == model) & (q1.horizon == h)].r2_oos.iloc[0]) for h in H]
            rows.append(f"{name} & " + " & ".join(f3(x) for x in v) + r" \\")
        q2 = t2[
            (t2.dataset == "fincall")
            & (t2.segment == "test")
            & (t2.target == "dv")
            & (t2.split == split)
            & (t2.model == "ridge_pastvol")
        ]
        v = [float(q2[q2.horizon == h].r2_oos.iloc[0]) for h in H]
        rows.append("S0$'$ past-vol ridge & " + " & ".join(f3(x) for x in v) + r" \\")
        q4 = t4[
            (t4.dataset == "fincall")
            & (t4.segment == "test")
            & (t4.target == "dv")
            & (t4.split == split)
        ]
        for stage, name in (
            ("S1_GBDT", "S1 GBDT (ticker FE)"),
            ("S2_text", "S2 text ridge + vol"),
            ("S3_audio", "S3 audio ridge + vol"),
            ("S4_fusion", "S4 stack fusion"),
        ):
            cells = []
            for h in H:
                r = q4[(q4.stage == stage) & (q4.horizon == h)].iloc[0]
                mark = ""
                hp = r["holm_p_vs_stage1"]
                if pd.notna(hp) and hp < 0.05:
                    s1 = float(q4[(q4.stage == "S1_GBDT") & (q4.horizon == h)].r2_oos.iloc[0])
                    mark = "*" if r.r2_oos > s1 else r"\dag"
                cells.append(f3(float(r.r2_oos)) + mark)
            rows.append(f"{name} & " + " & ".join(cells) + r" \\")
        if split == "temporal":
            rows.append(r"\midrule")
    (OUT / "grid_main.tex").write_text(GRID_TEX.replace("@BODY@", NL.join(rows)), encoding="utf-8")


