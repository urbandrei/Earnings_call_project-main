CONTROLS_TEX = r"""% Generated by make_main_tables.py from four controls CSVs.
\begin{table}[t]
\centering
\scriptsize
\setlength{\tabcolsep}{3pt}
\begin{tabular}{lrr}
\toprule
Identity probe (linear, frozen call embedding) & accuracy & $\times$chance \\
\midrule
@PROBE@
\bottomrule
\end{tabular}

\vspace{0.2em}
\begin{tabular}{lrrrr}
\toprule
Content swap (\Rtwo{} on $\Delta v$) & $\tau$=3 & $\tau$=7 & $\tau$=15 & $\tau$=30 \\
\midrule
@SHUF@
\bottomrule
\end{tabular}
\caption{\textbf{Identity checks.} Frozen embeddings identify the company far
above chance. Where companies recur (temporal), giving a test call another call
by the \emph{same} company barely changes the text model, while a random call
hurts. On the date-ordered company-disjoint split the real transcript scores no
better than either swap. The audio swaps are in Appendix Table~\ref{tab:audio}.}
\label{tab:controls}
\end{table}
"""


def controls_main() -> None:
    cp = pd.read_csv(R / "controls_probe.csv")
    ap = pd.read_csv(R / "audio_probe.csv")
    rc = pd.read_csv(R / "result_controls.csv")
    ash = pd.read_csv(R / "audio_shuffle.csv")
    probe: list[str] = []

    def probe_row(label: str, r: pd.Series) -> str:
        acc = f"{100 * r.probe_accuracy:.1f}\\%"
        chance = f"{r.accuracy_over_chance:.0f}$\\times$"
        return f"{label} ({int(r.n_tickers)} tickers) & {acc} & {chance} \\\\"

    for _, r in cp.iterrows():
        corpus = "FinCall" if r.dataset == "fincall" else "MAEC"
        probe.append(probe_row(f"BGE-M3 text, {corpus}", r))
    for _, r in ap.iterrows():
        emb = "WavLM" if r.embedding == "wavlm" else "emotion2vec+"
        probe.append(probe_row(f"{emb} audio, FinCall", r))

    conds = (
        ("real", "real"),
        ("within_shuffle", "same-company swap"),
        ("global_shuffle", "random swap"),
    )

    def text_block(split: str) -> list[str]:
        q = rc[
            (rc.dataset == "fincall")
            & (rc.segment == "test")
            & (rc.target == "dv")
            & (rc.split == split)
            & (rc.model == "ridge_text")
        ]
        out = []
        for cond, name in conds:
            v = [float(q[(q.condition == cond) & (q.horizon == h)].r2_oos.iloc[0]) for h in H]
            out.append(f"\\quad {name} & " + " & ".join(f3(x) for x in v) + r" \\")
        return out

    def audio_block(split: str) -> list[str]:
        q = ash[ash.split == split]
        out = []
        for cond, name in conds:
            v = [float(q[(q.condition == cond) & (q.horizon == h)].r2_oos.iloc[0]) for h in H]
            out.append(f"\\quad {name} & " + " & ".join(f3(x) for x in v) + r" \\")
        return out

    shuf = [r"\multicolumn{5}{l}{\textit{Text ridge, temporal split}}\\"]
    shuf += text_block("temporal")
    shuf.append(r"\multicolumn{5}{l}{\textit{Text ridge, date-ordered company-disjoint}}\\")
    shuf += text_block("combined")
    tex = CONTROLS_TEX.replace("@PROBE@", NL.join(probe)).replace("@SHUF@", NL.join(shuf))
    (OUT / "controls_main.tex").write_text(tex, encoding="utf-8")


